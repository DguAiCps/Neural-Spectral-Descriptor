#!/usr/bin/env python3
"""공식 createDescsAndRetrieve.m의 줄을 그대로 복사해 평가 어댑터 fresco_adapter.m을 만든다.

python3 scripts/fresco_official/matlab_gen.py [--out DIR]   (서버 호스트, 기본 DIR = NAS build/matlab)

공식 파일(FreSCo 2bf5cee)의 sha256을 확인한 뒤 아래 줄 범위를 바꾸지 않고 옮긴다.
  DESC    74-97   imresize 101 bilinear -> fft2/fftshift abs -> crop 31:71 -> applyGaussian
                  -> ImToPolar(0,1,20,120) -> log, 40D key, fresco 20x120
  MATKEYS 113-116 kd-tree 입력 행렬
  GAP     132-135 end_db_idx = query_idx - LOOP_FRAME_INTERVAL (값만 어댑터가 정한다)
  QUERY   137-162 createns kdtree + knnsearch K=20, 후보마다 computeFrescoDist(0:59 순환 L1),
                  행·열 cosine 거리, 각도
  WINNER  196-214 L1 최소(엄격 <) 후보 선택
  NESTED  282-377 applyGaussian ... computePoseDist (공식대로 부모 함수 안의 중첩 함수로 둔다;
                  angle_offset 등 공유 변수 의미가 같다)
어댑터가 바꾸는 것(protocol.json A1·A3): 입력 = csvread 대신 같은 정수값의 uint8 BEV 파일을
double로 읽음, LOOP_FRAME_INTERVAL = 인자(공통 규약 30, 원 조건 대조 100), 결과를 이진 파일로 기록.
부모 함수의 어댑터 변수는 모두 fx_ 접두어라 중첩 함수 변수와 겹치지 않는다.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OFFICIAL = REPO / "_external/fresco_official_20261107/FreSCo/fresco-matlab"
SHA = {"createDescsAndRetrieve.m": "579338855c91aa9a4902a490e208cb4c0eb78a57e517f0547eb30e7457d1a654",
       "ImToPolar.m": "0dcd1dc3ac426cbe26b8e0668579349d1606fbb89fb823cdc9b1faf0b0a8008c"}
RANGES = {"DESC": (74, 97), "MATKEYS": (113, 116), "GAP": (132, 135), "QUERY": (137, 162),
          "WINNER": (196, 214), "NESTED": (282, 377)}
NAS = Path(os.environ.get("FRESCO_NAS_ROOT", "/mnt/aicps-nas/qkrrlans00/nsd_fresco_official_20261107"))


def block(lines, name, indent=""):
    a, b = RANGES[name]
    body = lines[a - 1:b]
    return [f"% ---- official createDescsAndRetrieve.m:{a}-{b} ({name}) verbatim ----"] + \
           [indent + ln for ln in body] + [f"% ---- end {name} ----"]


def generate(out_dir: Path) -> dict:
    for f, h in SHA.items():
        got = hashlib.sha256((OFFICIAL / f).read_bytes()).hexdigest()
        assert got == h, (f, got)
    lines = (OFFICIAL / "createDescsAndRetrieve.m").read_text(encoding="utf-8").split("\n")
    src = []
    src += ["function fresco_adapter(fx_mode, fx_dir, fx_n, fx_gap)",
            "% GENERATED by scripts/fresco_official/matlab_gen.py from FreSCo 2bf5cee; do not edit.",
            "% fx_mode 'desc' : fx_dir/bev.u8 (fx_n x 224 x 224 uint8, C order, row = BEV x) ->",
            "%                  keys.f64 (fx_n x 40), fresco.f64 (fx_n x 20 x 120), C order",
            "% fx_mode 'match': keys/fresco -> match.f64 (fx_n x 6: best_idx(1-based or -1), L1,",
            "%                  cos_row, cos_col, angle_deg, end_db_idx), cand.i32 (fx_n x 20, 0 = none)",
            "% fx_mode 'all'  : desc then match in one session. fx_gap = LOOP_FRAME_INTERVAL.",
            "fx_t0 = tic;",
            "num_keyframes = fx_n;",
            "LOOP_FRAME_INTERVAL = fx_gap;",
            "if any(strcmp(fx_mode, {'desc', 'all'}))",
            "    fx_fid = fopen(fullfile(fx_dir, 'bev.u8'), 'r');",
            "    fx_bev = fread(fx_fid, [224 * 224, fx_n], 'uint8=>uint8');",
            "    fclose(fx_fid);",
            "    assert(size(fx_bev, 2) == fx_n, 'bev.u8 frame count');",
            "    cell_keys = cell(num_keyframes, 1);",
            "    cell_fresco = cell(num_keyframes, 1);",
            "    for i = 1:num_keyframes",
            "        tmp_cloud_input = double(reshape(fx_bev(:, i), [224, 224])');  % == csvread of the official CSV"]
    src += block(lines, "DESC")
    src += ["    end",
            "    clear fx_bev;"]
    src += block(lines, "MATKEYS")
    src += ["    fx_fresco = zeros(120, 20, num_keyframes);",
            "    for fx_i = 1:num_keyframes",
            "        fx_fresco(:, :, fx_i) = cell_fresco{fx_i}';",
            "    end",
            "    fx_write(fullfile(fx_dir, 'keys.f64'), mat_keys', 'double');",
            "    fx_write(fullfile(fx_dir, 'fresco.f64'), fx_fresco, 'double');",
            "    clear fx_fresco;",
            "    fprintf('FRESCO_DESC_DONE n=%d sec=%.1f\\n', num_keyframes, toc(fx_t0));",
            "end",
            "if any(strcmp(fx_mode, {'match', 'all'}))",
            "    if strcmp(fx_mode, 'match')",
            "        fx_fid = fopen(fullfile(fx_dir, 'keys.f64'), 'r');",
            "        mat_keys = fread(fx_fid, [40, fx_n], 'double')';",
            "        fclose(fx_fid);",
            "        fx_fid = fopen(fullfile(fx_dir, 'fresco.f64'), 'r');",
            "        fx_fresco = reshape(fread(fx_fid, 120 * 20 * fx_n, 'double'), [120, 20, fx_n]);",
            "        fclose(fx_fid);",
            "        cell_fresco = cell(num_keyframes, 1);",
            "        for fx_i = 1:num_keyframes",
            "            cell_fresco{fx_i} = fx_fresco(:, :, fx_i)';",
            "        end",
            "        clear fx_fresco;",
            "    end",
            "    fx_match = -ones(6, num_keyframes);",
            "    fx_cand = zeros(20, num_keyframes, 'int32');",
            "    fx_t1 = tic;",
            "    for query_idx = 1:num_keyframes"]
    src += block(lines, "GAP")
    src += block(lines, "QUERY")
    src += ["        fx_cand(1:size(key_candidates, 2), query_idx) = int32(key_candidates(1, :)');",
            "        candidates = key_dists_sorted;  % == cell_matches{query_idx}"]
    src += block(lines, "WINNER")
    src += ["        fx_match(:, query_idx) = [best_idx; min_fresco_dist; min_cosine_row_dist; ...",
            "                                  min_cosine_col_dist; matched_angle_offset; end_db_idx];",
            "        if mod(query_idx, 1000) == 0",
            "            fprintf('FRESCO_MATCH_PROGRESS %d/%d sec=%.1f\\n', query_idx, num_keyframes, toc(fx_t1));",
            "        end",
            "    end",
            "    fx_write(fullfile(fx_dir, 'match.f64'), fx_match, 'double');",
            "    fx_write(fullfile(fx_dir, 'cand.i32'), fx_cand, 'int32');",
            "    fprintf('FRESCO_MATCH_DONE n=%d sec=%.1f\\n', num_keyframes, toc(fx_t1));",
            "end",
            "",
            "function fx_write(fx_path, fx_val, fx_type)",
            "    fx_tmp = [fx_path '.tmp'];",
            "    fx_f = fopen(fx_tmp, 'w');",
            "    fx_c = fwrite(fx_f, fx_val, fx_type);",
            "    fclose(fx_f);",
            "    assert(fx_c == numel(fx_val), 'short write');",
            "    movefile(fx_tmp, fx_path, 'f');",
            "end",
            ""]
    src += block(lines, "NESTED")
    src += ["", "end", ""]
    out_dir.mkdir(parents=True, exist_ok=True)
    text = "\n".join(src)
    (out_dir / "fresco_adapter.m").write_text(text, encoding="utf-8")
    imp = (OFFICIAL / "ImToPolar.m").read_bytes()
    (out_dir / "ImToPolar.m").write_bytes(imp)          # 공식 파일 그대로
    rec = {"official_dir": str(OFFICIAL), "official_sha256": SHA, "ranges": RANGES,
           "blocks_sha256": {k: hashlib.sha256("\n".join(lines[a - 1:b]).encode()).hexdigest()
                             for k, (a, b) in RANGES.items()},
           "adapter": str(out_dir / "fresco_adapter.m"),
           "adapter_sha256": hashlib.sha256(text.encode()).hexdigest()}
    (out_dir / "matlab_gen.json").write_text(json.dumps(rec, indent=1))
    return rec


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(NAS / "build/matlab"))
    print(json.dumps(generate(Path(ap.parse_args().out)), indent=1))
